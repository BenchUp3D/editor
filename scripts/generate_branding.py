#!/usr/bin/env python3
"""Regenerate BenchUp's vector mark, platform icons, and egui geometry.

Requires Pillow: python3 -m pip install Pillow
Run from any directory: python3 scripts/generate_branding.py
"""
from pathlib import Path
import subprocess
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets' / 'branding'
RED = '#D94836'
FRONT = '#FFF9F2'
TOP = '#FFE0CD'
SIDE = '#F2A38B'
# An extruded workbench: a solid top, two legs, and a connecting rail.
# Shared geometry drives the SVG, raster assets, egui toolbar and PDF logo.
FACES = [
    (FRONT, [(28, 54), (42, 54), (42, 94), (28, 94)]),
    (FRONT, [(74, 54), (88, 54), (88, 94), (74, 94)]),
    ('#FFD0A6', [(42, 72), (74, 72), (74, 82), (42, 82)]),
    (FRONT, [(20, 42), (96, 42), (96, 56), (20, 56)]),
]
DEPTH = (12, -8)


def cross(a, b, c):
    return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])


def triangles(points):
    """Triangulate the concave front face for egui's mesh painter."""
    remaining = list(range(len(points)))
    result = []
    while len(remaining) > 3:
        for j, b in enumerate(remaining):
            a, c = remaining[j - 1], remaining[(j + 1) % len(remaining)]
            if cross(points[a], points[b], points[c]) <= 0:
                continue
            if any(all(cross(points[u], points[v], points[k]) >= 0
                       for u, v in [(a, b), (b, c), (c, a)])
                   for k in remaining if k not in (a, b, c)):
                continue
            result.extend([a, b, c])
            remaining.pop(j)
            break
        else:
            raise ValueError('Cannot triangulate logo')
    return result + remaining


def surfaces():
    faces = []
    for _, face in FACES:
      for a, b in zip(face, face[1:] + face[:1]):
        # Only the edges facing the extrusion vector are visible.
        if (b[1] - a[1]) * DEPTH[0] - (b[0] - a[0]) * DEPTH[1] > 0:
            points = [a, (a[0] + DEPTH[0], a[1] + DEPTH[1]),
                      (b[0] + DEPTH[0], b[1] + DEPTH[1]), b]
            faces.append((TOP if b[0] > a[0] else SIDE, points))
    return faces


def svg(square=True):
    background = f'  <rect width="128" height="128" rx="28" fill="{RED}"/>\n' if square else ''
    paths = surfaces() + FACES
    if not square:
        paths = [('#F07961' if color == TOP else '#A62E25', points)
                 for color, points in surfaces()] + [(RED, face) for _, face in FACES]
    polygons = '\n'.join(f'  <polygon fill="{color}" points="' +
                         ' '.join(f'{x},{y}' for x, y in points) + '"/>'
                         for color, points in paths)
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" role="img" aria-labelledby="title">\n'
            '  <title id="title">BenchUp</title>\n' + background + polygons + '\n</svg>\n')


def raster(size, rounded=True, padding=0):
    scale = 8
    image = Image.new('RGBA', (size * scale, size * scale), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    unit = size * scale / 128
    draw.rounded_rectangle((0, 0, size * scale - 1, size * scale - 1),
                           radius=28 * unit if rounded else 0, fill=RED)
    for color, points in surfaces() + FACES:
        draw.polygon([((padding + x * (1 - padding / 64)) * unit,
                       (padding + y * (1 - padding / 64)) * unit)
                      for x, y in points], fill=color)
    return image.resize((size, size), Image.Resampling.LANCZOS)


def macos_raster(size):
    """Place the badge on Apple's icon grid so it matches other Dock icons.

    macOS app icons draw an 824 px rounded rectangle centred on a 1024 px
    canvas with a soft drop shadow; a full-bleed badge looks oversized in the
    Dock and the app switcher.
    """
    scale = size / 1024
    badge = round(824 * scale)
    offset = (size - badge) // 2
    image = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    shadow = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    ImageDraw.Draw(shadow).rounded_rectangle(
        (offset, offset + round(10 * scale), offset + badge - 1, offset + badge - 1 + round(10 * scale)),
        radius=badge * 28 / 128, fill=(0, 0, 0, 77))
    image.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(max(1, 10 * scale))))
    image.alpha_composite(raster(badge), (offset, offset))
    return image


def rgb(hex_color):
    return ', '.join(str(int(hex_color[i:i + 2], 16)) for i in (1, 3, 5))


def rust():
    lines = ['// Generated by scripts/generate_branding.py; edit the source geometry there.',
             'use eframe::egui::{self, Color32, Rect};', '',
             'pub fn paint(p: &egui::Painter, rect: Rect) {',
             '    let size = rect.width().min(rect.height());',
             '    let origin = rect.center() - egui::vec2(size, size) * 0.5;',
             '    let point = |x: f32, y: f32| origin + egui::vec2(x, y) * (size / 128.);',
             f'    p.rect_filled(Rect::from_min_size(origin, egui::vec2(size, size)), (size * 28. / 128.).round() as u8, Color32::from_rgb({rgb(RED)}));']
    for color, points in surfaces():
        coords = ', '.join(f'point({x}., {y}.)' for x, y in points)
        lines.append(f'    p.add(egui::Shape::convex_polygon(vec![{coords}], Color32::from_rgb({rgb(color)}), egui::Stroke::NONE));')
    for color, points in FACES:
        lines.append('    let mut face = egui::Mesh::default();')
        for x, y in points:
            lines.append(f'    face.colored_vertex(point({x}., {y}.), Color32::from_rgb({rgb(color)}));')
        lines.append('    face.indices = vec![' + ', '.join(map(str, triangles(points))) + '];')
        lines.append('    p.add(egui::Shape::mesh(face));')
    lines.extend(['}', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'logo.svg').write_text(svg())
    (OUT / 'mark.svg').write_text(svg(square=False))
    for size in [16, 32, 48, 180, 192, 256, 512, 1024]:
        raster(size).save(OUT / f'icon-{size}.png')
    # Apple touch icons and maskable icons need opaque backgrounds.
    raster(180, rounded=False).save(OUT / 'apple-touch-icon.png')
    raster(512, rounded=False, padding=8).save(OUT / 'icon-maskable-512.png')
    raster(256).save(OUT / 'favicon.ico', sizes=[(16, 16), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    # macOS uses padded artwork for both the bundle and the runtime Dock icon.
    macos_raster(512).save(OUT / 'icon-macos-512.png')
    macos_raster(1024).save(OUT / 'benchup.icns')
    rust_path = ROOT / 'crates/benchup-app/src/brand_mark.rs'
    rust_path.write_text(rust())
    subprocess.run(['rustfmt', '--edition', '2024', str(rust_path)], check=True)
